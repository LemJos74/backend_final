-- LimpiaHuancayo v1.0 - Esquema PostgreSQL
-- Ejecutar conectado a una base de datos vacia de LimpiaHuancayo.
BEGIN;

CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    CONSTRAINT ck_roles_nombre_no_vacio CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE IF NOT EXISTS distritos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    CONSTRAINT ck_distritos_nombre_no_vacio CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE IF NOT EXISTS tipos_reporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(300),
    CONSTRAINT ck_tipos_nombre_no_vacio CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE IF NOT EXISTS estados_reporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    CONSTRAINT ck_estados_nombre_no_vacio CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    rol_id BIGINT NOT NULL REFERENCES roles(id),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuarios_nombre_no_vacio CHECK (length(btrim(nombre)) > 0),
    CONSTRAINT ck_usuarios_email_no_vacio CHECK (length(btrim(email)) > 0),
    CONSTRAINT ck_usuarios_password_hash_no_vacio CHECK (length(btrim(password_hash)) > 0)
);

-- Unicidad de correo sin distinguir mayusculas y minusculas.
CREATE UNIQUE INDEX IF NOT EXISTS ux_usuarios_email_normalizado
    ON usuarios (lower(btrim(email)));
CREATE INDEX IF NOT EXISTS ix_usuarios_rol_id ON usuarios(rol_id);

CREATE TABLE IF NOT EXISTS reportes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    distrito_id BIGINT NOT NULL REFERENCES distritos(id),
    tipo_id BIGINT NOT NULL REFERENCES tipos_reporte(id),
    estado_id BIGINT NOT NULL REFERENCES estados_reporte(id),
    descripcion TEXT NOT NULL,
    ubicacion VARCHAR(250) NOT NULL,
    latitud NUMERIC(10,8) NOT NULL,
    longitud NUMERIC(11,8) NOT NULL,
    imagen_path TEXT,
    observacion_admin TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_reportes_descripcion_no_vacia CHECK (length(btrim(descripcion)) > 0),
    CONSTRAINT ck_reportes_ubicacion_no_vacia CHECK (length(btrim(ubicacion)) > 0),
    CONSTRAINT ck_reportes_latitud CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_reportes_longitud CHECK (longitud BETWEEN -180 AND 180)
);

CREATE INDEX IF NOT EXISTS ix_reportes_usuario_id ON reportes(usuario_id);
CREATE INDEX IF NOT EXISTS ix_reportes_distrito_id ON reportes(distrito_id);
CREATE INDEX IF NOT EXISTS ix_reportes_tipo_id ON reportes(tipo_id);
CREATE INDEX IF NOT EXISTS ix_reportes_estado_id ON reportes(estado_id);
CREATE INDEX IF NOT EXISTS ix_reportes_created_at ON reportes(created_at DESC);

COMMIT;
